package Operators_And_Control_Statements_03.Operators_01.Relational_Operators_03;

public class RelationalOperators_01 {

    public static void main(String[] args) {
        int a = 10, b = 20;
        System.out.println("a < b = " + (a < b));
        System.out.println("a > b = " + (a > b));
        System.out.println("a <= b = " + (a <= b));
        System.out.println("a >= b = " + (a >= b));
        System.out.println("a == b = " + (a == b));
        System.out.println("a != b = " + (a != b));
    }
}
