package DataTypes_And_Variables_02.Data_Types_02;

public class Primitive_DataTypes_01 {

    public static void main(String[] args) {
        byte b = 10;
        short s = 200;
        int i = 100000;
        long l = 10000000000L;
        float f = 3.14f;
        double d = 3.14159;
        char c = 'A';
        boolean flag = true;
        System.out.printf("byte=%d short=%d int=%d long=%d float=%f double=%f char=%c boolean=%b%n",
                b, s, i, l, f, d, c, flag);
    }
}
