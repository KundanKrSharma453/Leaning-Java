package DataTypes_And_Variables_02.Data_Types_02;

public class Literals_05 {

    public static void main(String[] args) {
        int decimal = 100;
        int hex = 0x64;      // hexadecimal literal
        int binary = 0b1100100; // binary literal
        long bigNumber = 100L;
        double sci = 1.5e2;   // scientific notation
        char letter = 'A';
        String text = "literal";
        System.out.println(decimal + " " + hex + " " + binary + " " + bigNumber + " " + sci + " " + letter + " " + text);
    }
}
